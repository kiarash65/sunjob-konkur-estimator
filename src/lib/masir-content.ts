/** Convert a string to a URL-safe slug (lowercase, hyphen-separated).
 *  Non-alphanumerics collapse to hyphens, leading/trailing hyphens trimmed.
 *  Persian/Arabic characters are NOT transliterated here — we only slugify
 *  the englishName fields which are already ASCII. */
export function slugify(input: string): string {
  return input
    .toLowerCase()
    .trim()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
}

