/** Look up a major by its Persian `name` field. Kept for backward
 * compatibility with the existing UI; new code should prefer getMajorBySlug.
 * Falls back to a slug match if no name matches (so passing a slug still works
 * for callers that haven't been migrated yet). */
export function getMajorDescription(name: string): MajorDescription | null {
  const found =
    MAJOR_DESCRIPTIONS.find((m) => m.name === name) ??
    MAJOR_DESCRIPTIONS.find((m) => m.slug === name)
  return found ?? null
}

/** Look up a major by its URL slug. Returns undefined if no match. */
export function getMajorBySlug(slug: string): MajorDescription | undefined {
  return MAJOR_DESCRIPTIONS.find((m) => m.slug === slug)
}

export function getMajorByName(name: string): MajorDescription | null {
  const found = MAJOR_DESCRIPTIONS.find((m) => m.name === name)
  return found ?? null
}

