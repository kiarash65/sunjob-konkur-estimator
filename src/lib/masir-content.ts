/** Look up a guide by its URL slug. Returns undefined if no match. */
export function getGuideBySlug(slug: string): GuideItem | undefined {
  return GUIDES.find((g) => g.slug === slug)
}

/** Alias kept for backward compatibility with existing callers
 *  (e.g. /app/guides/[slug]/page.tsx). Prefer getGuideBySlug in new code. */
export function getGuide(slug: string): GuideItem | null {
  return getGuideBySlug(slug) ?? null
}

// ───────────── University entity (extends UniversityInfo with slug + short description) ─────────────

export interface UniversityEntity {
  name: string;
  slug: string;
  type: string;       // matches a UNI_TYPE_CATEGORIES.id (mapped from UniversityType)
  typeLabel: string;
  city: string;
  province: string;   // for our purposes, province ~= city (no real province dataset)
  shortDescription: string;
  majorCount?: number;
}

/**
 * Map internal UniversityType ("dolati" | "azad" | ...) to masir-style snake_case
 * UNI_TYPE_CATEGORIES.id ("state_public" | "islamic_azad" | ...). For our dataset
 * we only have 6 types in use; the others (military_security, religious, virtual)
 * are still defined in UNI_TYPE_CATEGORIES but no current universities map to them.
 */
export function mapUniType(internalType: string): string {
  switch (internalType) {
    case 'dolati': return 'state_public'
    case 'azad': return 'islamic_azad'
    case 'payamnoor': return 'payam_noor'
    case 'ghayrentefai': return 'nonprofit'
    case 'elmikarbordi': return 'applied_science'
    case 'fanhariyan': return 'teacher_training'
    // We don't currently have data for these, but keep the mapping symmetric.
    case 'teb': return 'medical_sciences'
    case 'nizami': return 'military_security'
    case 'mazhabi': return 'religious'
    case 'majazi': return 'virtual'
    default: return 'state_public'
  }
}

export function getUniTypeLabel(internalType: string): string {
  const id = mapUniType(internalType)
  return UNI_TYPE_CATEGORIES.find((c) => c.id === id)?.title ?? 'دانشگاه'
}

